function main() {
  if (!fs.existsSync(ISSUE_DIR)) throw new Error(`Missing issue dir: ${ISSUE_DIR}`);
  for (const [dirName, title, lead] of articles) {
    const dir = path.join(ISSUE_DIR, dirName);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, `${dirName.replace(/^\d+_/, '')}.html`), articleHtml(title, lead), 'utf8');
  }
  console.log(`seeded ${articles.length} articles for ${ISSUE}`);
}

main();